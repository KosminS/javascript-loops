// Вибираємо число, для якого потрібна таблиця множення
const number = 8;

// Початкове значення лічильника
let i = 1;

// Цикл while, який працює, поки лічильник менший або дорівнює 10
while (i <= 10) {
    const result = number * i;
    console.log(number, "x", i, "=", result);
    i++; // Збільшуємо лічильник на 1
}